using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Numerics;
using System.Text;
using System.Text.RegularExpressions;
using AnoMech.Core.Native.Interfaces;
using AnoMech.Learn.Sources;

namespace AnoMech.Learn.Tools;

// The three files a new scenario family starts from, written from one recorded pull: the ids
// with the game's names, one EnemyAction per enemy action with the sheet's shape, and the
// timeline as the log saw it, spawns and casts at their observed times. Rolls, strats and the
// state stay for the author: every place the pull's own luck shows is marked TODO.
public sealed record SkeletonFiles(string Constants, string Actions, string Scenario, IReadOnlyList<string> Notes);

public static class ScenarioSkeleton
{
    public const uint HelperBNpcBase = 9020;
    // Base ids of the helper rows every fight shares; their casts come from an invisible helper.
    private static readonly HashSet<uint> HelperBases = [HelperBNpcBase, 0x233C];

    public static SkeletonFiles Generate(ActPull pull, string family, string phase, Vector3 origin, float t0, IGameData? data, ModuleSource? modules)
    {
        var notes = new List<string>();
        var names = new Names();

        // Actors: one field per distinct enemy base, numbered when the base spawns more than once.
        var spawns = pull.Events.OfType<ActSpawn>().GroupBy(s => s.Actor.Id).Select(g => g.First()).ToList();
        var casters = pull.Events.OfType<ActCast>().Select(c => c.Caster).Concat(pull.Events.OfType<ActAbility>().Select(a => a.Caster))
            .GroupBy(a => a.Id).Select(g => g.First()).ToList();
        foreach (var caster in casters.Where(c => spawns.All(s => s.Actor.Id != c.Id)))
        {
            notes.Add($"{caster.Name} [{caster.Id:X8}] casts but never spawns in the pull: present from zone-in, spawned at the origin");
            spawns.Add(new ActSpawn(0f, caster, 0, 0, 0, origin, 0f));
        }
        var actors = new Dictionary<uint, string>();
        var byBase = spawns.GroupBy(s => (s.BaseId, s.NameId)).ToList();
        foreach (var group in byBase)
        {
            var baseName = group.Key.BaseId == 0 ? names.Pascal(group.First().Actor.Name, "Actor") : IsHelper(group.Key.BaseId) ? "Helper" : names.Pascal(group.First().Actor.Name, $"BNpc{group.Key.BaseId:X}");
            var list = group.OrderBy(s => s.T).ToList();
            for (var i = 0; i < list.Count; i++)
                actors[list[i].Actor.Id] = Camel(baseName) + (list.Count > 1 ? (i + 1).ToString(CultureInfo.InvariantCulture) : "");
        }

        var constants = Constants(pull, family, spawns, names, notes);
        var actions = Actions(pull, family, names, data, modules, notes);
        var scenario = Scenario(pull, family, phase, origin, t0, spawns, actors, names, notes);
        return new SkeletonFiles(constants, actions, scenario, notes);
    }

    private static bool IsHelper(uint baseId) => HelperBases.Contains(baseId);

    // ── Constants ────────────────────────────────────────────────────────────

    private static string Constants(ActPull pull, string family, List<ActSpawn> spawns, Names names, List<string> notes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine();
        sb.AppendLine($"namespace AnoMech.Scenarios.{family};");
        sb.AppendLine();
        sb.AppendLine("// Generated by scenario-skeleton from a recorded pull; names are the game's, ids the log's.");
        sb.AppendLine($"public static class {family}Constants");
        sb.AppendLine("{");
        var level = spawns.Where(s => s.Level > 0 && !IsHelper(s.BaseId)).Select(s => s.Level).DefaultIfEmpty((byte)0).Max();
        sb.AppendLine($"    public const byte Level = {level};");
        var director = pull.Events.OfType<ActDirector>().Select(d => d.Instance).FirstOrDefault(i => i >> 16 == 0x8003);
        sb.AppendLine(director != 0 ? $"    public const uint DirectorEventId = 0x{director:X8};" : "    public const uint DirectorEventId = 0; // TODO: no director line in the pull");
        sb.AppendLine();
        sb.AppendLine("    public static class BNpcBaseId");
        sb.AppendLine("    {");
        foreach (var s in spawns.Where(s => s.BaseId != 0).GroupBy(s => s.BaseId).Select(g => g.First()).OrderBy(s => s.T))
            sb.AppendLine($"        public const uint {names.Constant("bnpc", s.BaseId, IsHelper(s.BaseId) ? "Helper" : s.Actor.Name)} = {s.BaseId};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static class BNpcNameId");
        sb.AppendLine("    {");
        foreach (var s in spawns.Where(s => s.NameId != 0).GroupBy(s => s.NameId).Select(g => g.First()).OrderBy(s => s.T))
            sb.AppendLine($"        public const uint {names.Constant("bnpcname", s.NameId, s.Actor.Name)} = {s.NameId};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static class ActionId");
        sb.AppendLine("    {");
        foreach (var (id, name) in ActionIds(pull))
            sb.AppendLine($"        public const uint {names.Constant("action", id, name)} = 0x{id:X};");
        sb.AppendLine("    }");
        var statuses = pull.Events.OfType<ActStatus>().Where(s => s.Gained && s.Target.IsPlayer).GroupBy(s => s.StatusId).Select(g => g.First()).OrderBy(s => s.T).ToList();
        if (statuses.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("    public static class StatusId");
            sb.AppendLine("    {");
            foreach (var s in statuses)
                sb.AppendLine($"        public const ushort {names.Constant("status", s.StatusId, s.Name)} = 0x{s.StatusId:X};");
            sb.AppendLine("    }");
        }
        var markers = pull.Events.OfType<ActMarker>().GroupBy(m => m.MarkerId).Select(g => g.First()).OrderBy(m => m.T).ToList();
        if (markers.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("    public static class LockonId");
            sb.AppendLine("    {");
            foreach (var m in markers)
                sb.AppendLine($"        public const uint {names.Constant("lockon", m.MarkerId, $"Marker{m.MarkerId:X}")} = 0x{m.MarkerId:X}; // TODO: name it (first at {F(m.T)}s on {m.Target.Name})");
            sb.AppendLine("    }");
        }
        var tethers = pull.Events.OfType<ActTether>().GroupBy(t => t.TetherId).Select(g => g.First()).OrderBy(t => t.T).ToList();
        if (tethers.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("    public static class TetherId");
            sb.AppendLine("    {");
            foreach (var t in tethers)
                sb.AppendLine($"        public const ushort {names.Constant("tether", t.TetherId, $"Tether{t.TetherId:X}")} = 0x{t.TetherId:X}; // TODO: name it (first at {F(t.T)}s, {t.Source.Name} -> {t.Target.Name})");
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static List<(uint Id, string Name)> ActionIds(ActPull pull)
        => pull.Events.OfType<ActCast>().Select(c => (c.T, c.ActionId, c.Name))
            .Concat(pull.Events.OfType<ActAbility>().Select(a => (a.T, a.ActionId, a.Name)))
            .GroupBy(x => x.ActionId).Select(g => g.OrderBy(x => x.T).First()).OrderBy(x => x.T).Select(x => (x.ActionId, x.Name)).ToList();

    // ── Actions ──────────────────────────────────────────────────────────────

    private static string Actions(ActPull pull, string family, Names names, IGameData? data, ModuleSource? modules, List<string> notes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("using System;");
        sb.AppendLine("using AnoMech.Core.EnemyActions;");
        sb.AppendLine("using static AnoMech.Core.EnemyActions.EnemyActionEffects;");
        sb.AppendLine($"using static AnoMech.Scenarios.{family}.{family}Constants;");
        sb.AppendLine();
        sb.AppendLine($"namespace AnoMech.Scenarios.{family};");
        sb.AppendLine();
        sb.AppendLine("// Generated by scenario-skeleton: one EnemyAction per enemy action the pull showed, shape from");
        sb.AppendLine("// the Action sheet, the one dimension the sheet lacks marked UNVERIFIED unless a public module");
        sb.AppendLine("// names it. Animation locks and damage delays are placeholders to measure.");
        sb.AppendLine($"public static class {family}Actions");
        sb.AppendLine("{");
        var abilities = pull.Events.OfType<ActAbility>().ToList();
        var statusesByAction = StatusesByAction(pull);
        var first = true;
        foreach (var (id, name) in ActionIds(pull))
        {
            var constant = names.Constant("action", id, name);
            var row = data?.Action(id);
            var hits = abilities.Where(a => a.ActionId == id && a.Target is { IsPlayer: true }).ToList();
            var damages = hits.Count(h => h.Damage is > 0);
            if (!first) sb.AppendLine();
            first = false;
            var comment = new List<string>();
            if (row is { } r) comment.Add($"{ShapeWord(r.CastType)}{(r.EffectRange > 0 ? $" {r.EffectRange}y" : "")}{(r.XAxisModifier > 0 ? $" width {r.XAxisModifier}" : "")}, cast {F(r.CastSeconds)}s");
            else comment.Add("not in the Action sheet");
            comment.Add(hits.Count == 0 ? "hit nobody" : $"hit {hits.Count} player{(hits.Count == 1 ? "" : "s")}{(damages > 0 ? $", {damages} for damage" : "")}");
            if (modules?.Sources.Select(s => s.Action(id)).FirstOrDefault(f => f != null) is { } fact && fact.Shape is { } shape)
                comment.Add($"modules: {shape.Kind}{(shape.Range is { } rg ? $" {F(rg)}" : "")}{(shape.Angle is { } an ? $" {F(an)}°" : "")}{(shape.Inner is { } inn ? $" hole {F(inn)}" : "")}");
            sb.AppendLine($"    // {string.Join("; ", comment)}");
            sb.AppendLine($"    public static readonly EnemyAction {constant} = new(ActionId.{constant})");
            sb.AppendLine("    {");
            sb.AppendLine("        Cast = new() { AnimationLock = 0.6f },");
            if (row is { CastType: CastType.Cone or CastType.Cone2 or CastType.Donut } cone)
            {
                var size = SizeFromModules(id, cone.CastType, modules, out var sizeNote);
                sb.AppendLine(size is { } s
                    ? $"        Area = new() {{ Size = {s} }},{(sizeNote is { } n ? $" // {n}" : "")}"
                    : $"        Area = new() {{ Size = null }}, // UNVERIFIED: {(cone.CastType == CastType.Donut ? "the hole's radius" : "the cone's half-angle")}; the sheet has none");
            }
            else if (row is { CastType: CastType.Custom })
                sb.AppendLine("        Area = new() { CastTypeOverride = null }, // TODO: the sheet says Custom; pick the shape");
            var effects = new List<string>();
            if (damages > 0) effects.Add("Damage()");
            foreach (var (statusId, statusName, duration) in statusesByAction.GetValueOrDefault(id, []))
                effects.Add($"ApplyStatus(StatusId.{names.Constant("status", statusId, statusName)}, {F(duration)}f)");
            sb.AppendLine(effects.Count == 0
                ? "        Effects = [], // TODO: nothing reached a player in this pull"
                : $"        Effects = [{string.Join(", ", effects)}],");
            sb.AppendLine("        Timing = new() { DamageDelay = 0.4f }, // placeholder");
            sb.AppendLine("    };");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    // A status a player gains within a second of an enemy action landing on them, from the same source.
    private static Dictionary<uint, List<(ushort Id, string Name, float Duration)>> StatusesByAction(ActPull pull)
    {
        var result = new Dictionary<uint, List<(ushort, string, float)>>();
        var gains = pull.Events.OfType<ActStatus>().Where(s => s.Gained && s.Target.IsPlayer).ToList();
        foreach (var hit in pull.Events.OfType<ActAbility>().Where(a => a.Target is { IsPlayer: true }))
        {
            foreach (var gain in gains.Where(g => g.Target.Id == hit.Target!.Id && g.T >= hit.T - 0.05f && g.T <= hit.T + 1f && (g.Source.Id == hit.Caster.Id || g.Source.Id == 0xE0000000)))
            {
                var list = result.TryGetValue(hit.ActionId, out var l) ? l : result[hit.ActionId] = [];
                if (list.All(x => x.Item1 != gain.StatusId)) list.Add((gain.StatusId, gain.Name, gain.Duration));
            }
        }
        return result;
    }

    private static string? SizeFromModules(uint actionId, CastType type, ModuleSource? modules, out string? note)
    {
        note = null;
        if (modules is null) return null;
        var values = new List<(string Source, float Value)>();
        foreach (var source in modules.Sources)
        {
            if (source.Action(actionId) is not { } fact) continue;
            var shapes = source.ShapesFor(fact.Name).ToList();
            if (fact.Shape is { } own) shapes.Insert(0, own);
            foreach (var shape in shapes)
            {
                if (type == CastType.Donut && shape.Inner is { } inner) values.Add((source.Name, inner));
                else if (type != CastType.Donut && shape.Angle is { } angle) values.Add((source.Name, angle));
            }
        }
        var distinct = values.Select(v => v.Value).Distinct().ToList();
        if (distinct.Count == 0) return null;
        var picked = distinct[0];
        note = distinct.Count == 1
            ? $"from the public modules ({string.Join("/", values.Select(v => v.Source).Distinct())})"
            : $"UNVERIFIED: the modules disagree ({string.Join(", ", values.Select(v => $"{v.Source} {F(v.Value)}"))}); the first is used";
        return type == CastType.Donut ? $"{F(picked)}f" : $"MathF.PI * {F(picked / 360f)}f";
    }

    private static string ShapeWord(CastType type) => type switch
    {
        CastType.Circle or CastType.Circle2 or CastType.GroundCircle => "circle",
        CastType.Cone or CastType.Cone2 => "cone",
        CastType.Rectangle or CastType.Rectangle2 or CastType.Charge => "line",
        CastType.Donut => "donut",
        CastType.Cross => "cross",
        CastType.SingleTarget => "single target",
        CastType.Custom => "custom",
        _ => "no area",
    };

    // ── Scenario ─────────────────────────────────────────────────────────────

    private static string Scenario(ActPull pull, string family, string phase, Vector3 origin, float t0, List<ActSpawn> spawns, Dictionary<uint, string> actors, Names names, List<string> notes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine("using AnoMech.Core.Game;");
        sb.AppendLine("using AnoMech.Core.Game.Ai;");
        sb.AppendLine("using AnoMech.Core.SimObjects;");
        sb.AppendLine($"using static AnoMech.Scenarios.{family}.{family}Constants;");
        sb.AppendLine($"using Actions = AnoMech.Scenarios.{family}.{family}Actions;");
        sb.AppendLine();
        sb.AppendLine($"namespace AnoMech.Scenarios.{family}.{phase};");
        sb.AppendLine();
        sb.AppendLine($"// Generated by scenario-skeleton from pull {pull.Index} ({F(pull.Duration)}s, {(pull.Clear ? "clear" : "wipe")}); times from {(t0 == 0f ? "the pull's start" : $"{F(t0)}s into the pull")}.");
        sb.AppendLine("// The timeline is the log's; targets, spots and anything that varied between pulls are TODO rolls.");
        sb.AppendLine($"public sealed class {family}{phase}Scenario : IScenario");
        sb.AppendLine("{");
        sb.AppendLine($"    public string Name => \"{phase}\";");
        sb.AppendLine($"    public IPhase Phase => {family}Zone.Fight; // TODO: the phase");
        sb.AppendLine();
        sb.AppendLine("    public IReadOnlyList<IScenarioAi> AiStrats => []; // TODO: the strat lives in *Ai.cs");
        sb.AppendLine();
        var fields = actors.Values.Distinct().OrderBy(v => v, StringComparer.Ordinal).ToList();
        sb.AppendLine("    private SimWorld world = null!;");
        foreach (var field in fields) sb.AppendLine($"    private SimEnemy? {field};");
        sb.AppendLine();
        sb.AppendLine("    public void Run(SimWorld worldParam, int? selectedAi)");
        sb.AppendLine("    {");
        sb.AppendLine("        world = worldParam;");
        sb.AppendLine("        world.Events.Add(0f, SpawnActors);");

        var casts = pull.Events.OfType<ActCast>().ToList();
        var lines = new List<(float T, string Line)>();
        foreach (var s in spawns.Where(s => s.T - t0 > 1f))
            lines.Add((s.T, $"        world.Events.Add({T(s.T - t0)}, () => {actors[s.Actor.Id]} = {SpawnCall(s, origin, names, "            ")});"));
        foreach (var cast in casts)
        {
            var actor = actors[cast.Caster.Id];
            var action = names.Constant("action", cast.ActionId, cast.Name);
            var target = cast.Target is { IsPlayer: true } p ? $" /* TODO roll: on {p.Name} */" : cast.Target is { IsEnemy: true } e && actors.TryGetValue(e.Id, out var other) && other != actor ? $", {other}" : "";
            var moved = IsHelper(spawns.First(s => s.Actor.Id == cast.Caster.Id).BaseId) || Vector3.Distance(cast.Position, spawns.First(s => s.Actor.Id == cast.Caster.Id).Position) > 0.5f;
            var place = moved ? $"{actor}?.SetPosition(new Placement({Local(cast.Position, origin)}, {F(cast.Rotation)}f)); " : "";
            lines.Add((cast.T, $"        world.Events.Add({T(cast.T - t0)}, () => {{ {place}{actor}?.Cast(Actions.{action}{target}); }});"));
        }
        // An ability no cast bar announced is an instant; one that follows its own cast is the cast's resolve.
        foreach (var group in pull.Events.OfType<ActAbility>().GroupBy(a => (a.Caster.Id, a.ActionId, a.Sequence)))
        {
            var a = group.OrderBy(x => x.TargetIndex).First();
            if (casts.Any(c => c.Caster.Id == a.Caster.Id && c.ActionId == a.ActionId && a.T - c.T >= -0.1f && a.T - c.T <= c.CastTime + 1.5f)) continue;
            var actor = actors[a.Caster.Id];
            var action = names.Constant("action", a.ActionId, a.Name);
            var target = a.Target is { IsPlayer: true } p ? $" /* TODO roll: on {p.Name} */" : "";
            var moved = IsHelper(spawns.First(s => s.Actor.Id == a.Caster.Id).BaseId) || Vector3.Distance(a.CasterPosition, spawns.First(s => s.Actor.Id == a.Caster.Id).Position) > 0.5f;
            var place = moved ? $"{actor}?.SetPosition(new Placement({Local(a.CasterPosition, origin)}, {F(a.CasterRotation)}f)); " : "";
            lines.Add((a.T, $"        world.Events.Add({T(a.T - t0)}, () => {{ {place}{actor}?.Cast(Actions.{action}{target}); }}); // instant, {group.Count()} target{(group.Count() == 1 ? "" : "s")}"));
        }
        foreach (var d in pull.Events.OfType<ActDirector>().Where(d => d.Instance >> 16 == 0x8003 && d.Command >> 28 != 4))
            lines.Add((d.T, $"        world.Events.Add({T(d.T - t0)}, () => world.Map.DirectorUpdate(0x{d.Command:X}, {string.Join(", ", d.Params.Select(p => $"0x{p:X}"))}));"));
        foreach (var m in pull.Events.OfType<ActMapEffect>())
            lines.Add((m.T, $"        world.Events.Add({T(m.T - t0)}, () => world.Map.AddEffect(0x{m.Flags:X8}, 0x{m.Index:X2}));"));
        foreach (var m in pull.Events.OfType<ActMarker>())
            lines.Add((m.T, $"        // {F(m.T - t0)}s: marker 0x{m.MarkerId:X} on {m.Target.Name} -- TODO roll"));
        foreach (var t in pull.Events.OfType<ActTether>())
            lines.Add((t.T, $"        // {F(t.T - t0)}s: tether 0x{t.TetherId:X} {t.Source.Name} -> {t.Target.Name} -- TODO roll"));
        foreach (var d in pull.Events.OfType<ActDespawn>().Where(d => actors.ContainsKey(d.Actor.Id)))
            lines.Add((d.T, $"        world.Events.Add({T(d.T - t0)}, () => {actors[d.Actor.Id]}?.Despawn());"));
        foreach (var (_, line) in lines.Where(l => l.T - t0 >= 0f).OrderBy(l => l.T)) sb.AppendLine(line);
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Tick(float delta, float elapsed) { }");
        sb.AppendLine();
        sb.AppendLine("    private void SpawnActors()");
        sb.AppendLine("    {");
        foreach (var s in spawns.Where(s => s.T - t0 <= 1f).OrderBy(s => s.T))
            sb.AppendLine($"        {actors[s.Actor.Id]} = {SpawnCall(s, origin, names, "            ")};");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string SpawnCall(ActSpawn s, Vector3 origin, Names names, string indent)
    {
        var helper = IsHelper(s.BaseId);
        var baseId = s.BaseId == 0 ? "0 /* TODO: BNpcBase */" : $"BNpcBaseId.{names.Constant("bnpc", s.BaseId, helper ? "Helper" : s.Actor.Name)}";
        var nameId = s.NameId == 0 ? "" : $",\n{indent}NameId: BNpcNameId.{names.Constant("bnpcname", s.NameId, s.Actor.Name)}";
        return $"world.SpawnEnemy(new EnemySpawnConfig(\n{indent}BNpcBaseId: {baseId}{nameId},\n{indent}Level: {(helper ? "1" : "Level")},"
               + (helper ? $"\n{indent}EnemyList: EnemyListMode.Never,\n{indent}Visibility: SpawnVisibility.InvisibleHelper," : $"\n{indent}Targetable: true,")
               + $"\n{indent}Placement: new Placement({Local(s.Position, origin)}, {F(s.Rotation)}f)))";
    }

    private static string Local(Vector3 position, Vector3 origin)
        => $"new Vector3({F(position.X - origin.X)}f, {F(position.Y - origin.Y)}f, {F(position.Z - origin.Z)}f)";

    private static string T(float seconds) => $"{F(seconds)}f";
    private static string F(float value) => value.ToString("0.##", CultureInfo.InvariantCulture);
    private static string Camel(string pascal) => pascal.Length == 0 ? pascal : char.ToLowerInvariant(pascal[0]) + pascal[1..];

    // The `world.Events.Add(<t>f, ... Actions.<Name>` lines of a generated scenario, for a check
    // that its timeline is the pull's.
    public static List<(float T, string Action)> TimelineOf(string scenarioSource)
        => Regex.Matches(scenarioSource, @"world\.Events\.Add\((?<t>[\d.]+)f, \(\) => \{.*?Actions\.(?<a>\w+)")
            .Select(m => (float.Parse(m.Groups["t"].Value, CultureInfo.InvariantCulture), m.Groups["a"].Value)).ToList();

    // Identifiers that are the game's names made into C#, unique per category; an id seen twice keeps its first name.
    private sealed class Names
    {
        private readonly Dictionary<(string Category, uint Id), string> byId = [];
        private readonly Dictionary<string, HashSet<string>> taken = [];

        public string Constant(string category, uint id, string name)
        {
            if (byId.TryGetValue((category, id), out var existing)) return existing;
            var set = taken.TryGetValue(category, out var s) ? s : taken[category] = [];
            var candidate = Pascal(name, $"Id{id:X}");
            var unique = candidate;
            var n = 2;
            while (!set.Add(unique)) unique = $"{candidate}{n++}";
            byId[(category, id)] = unique;
            return unique;
        }

        public string Pascal(string name, string fallback)
        {
            var words = Regex.Split(name, @"[^A-Za-z0-9]+").Where(w => w.Length > 0).Select(w => char.ToUpperInvariant(w[0]) + w[1..]);
            var result = string.Concat(words);
            if (result.Length == 0 || char.IsDigit(result[0])) return fallback;
            return result;
        }
    }
}
