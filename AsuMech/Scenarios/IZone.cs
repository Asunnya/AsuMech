using System.Collections.Generic;
using System.Numerics;
using AsuMech.Core.Game;
using AsuMech.Core.Map;
using AsuMech.Core.SimObjects;
using AsuMech.Core.UserActions;

namespace AsuMech.Scenarios;

// A raid territory: the identity every scenario inside it shares. Authored bottom-up —
// scenarios point at their IPhase, phases point here — and ScenarioCatalog derives the downward
// zone -> phase -> scenario view for the menu.
public interface IZone
{
    string Name { get; }

    // Menu grouping: the tab the zone sits under, then the expansion heading inside it
    // (null = no heading).
    string Category => "Ultimate";
    string? Expansion => null;

    // The fight's tab label ("UWU", "M9S").
    string ShortName => Name;

    // Savage sub-tier ("Heavyweight"); null for ultimates.
    string? Tier => null;
    uint TerritoryId { get; }
    Vector3 Origin { get; }

    // At least one; [0] is the default.
    IReadOnlyList<WaymarkLayout> WaymarkPresets { get; }

    // Generated by tools/replay_export_duty_init.py.
    DutyInitData DutyInitData { get; }

    // The floor a top-down view draws before a run sets its own fence (SimWorld.ArenaShape wins
    // while one runs); the scenarios' EnforceArenaBoundary stays the truth for deaths.
    Core.Game.Geometry.IArenaShape Arena => new Core.Game.Geometry.CircleArena(20f);
    // When a tank LB3's status lands; null: on its recipients at the press.
    StatusLanding? TankLimitBreakLanding => null;

    // Zone-wide setup, first in the cascade.
    void Run(SimWorld world) { }
}
